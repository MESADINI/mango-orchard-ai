#!/usr/bin/env python3
"""
Generates 001_seed_recommendations.sql from ml/forecasting/recommendations_db.json, the single verified source of
treatment advice, so the optional Supabase schema can never drift from what the app recommends.

    python database/seeds/generate_seed.py
"""

import json
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
DB_JSON = REPO_ROOT / "ml" / "forecasting" / "recommendations_db.json"
OUT = Path(__file__).with_name("001_seed_recommendations.sql")
COLUMNS = ("target_condition", "treatment_type", "title", "product_name", "active_ingredient", "dosage_rate",
           "application_guidance", "waiting_period_days", "citation_source", "citation_url")


def _sql(value) -> str:
    if value is None:
        return "NULL"
    if isinstance(value, int):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def render(db: dict) -> str:
    rows = []
    for condition, recs in db.items():
        if condition.startswith("_"):
            continue
        for r in recs:
            values = [condition] + [r.get(c) for c in COLUMNS[1:]]
            rows.append("    (" + ", ".join(_sql(v) for v in values) + ")")
    return (
        "-- AI Mango Orchard Health & Pest Intelligence\n"
        "-- GENERATED by database/seeds/generate_seed.py from ml/forecasting/recommendations_db.json; do not edit.\n"
        f"-- Sources verified on {db['_meta']['verified_on']} (see docs/sources.md).\n\n"
        "INSERT INTO public.treatment_recommendations\n(" + ", ".join(COLUMNS) + ")\nVALUES\n"
        + ",\n".join(rows) + ";\n"
    )


if __name__ == "__main__":
    OUT.write_text(render(json.loads(DB_JSON.read_text(encoding="utf-8"))), encoding="utf-8")
    print(OUT)
