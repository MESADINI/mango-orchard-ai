"""
Builds demo_data/images/ and demo_data/MANIFEST.md: sample images for the live demo plus the deployed models' actual
outputs on each. Selection is deterministic, with no filtering on the prediction:
- leaves: held-out TEST split only, sorted by SHA-256. First 2 each of Anthracnose, Bacterial Canker, Powdery
  Mildew and Sooty Mold, then the first Healthy.
- pest: the first Fruit Fly trap image of the pest TEST split (sorted by SHA-256).
- unsure: the first external-set image (sorted by SHA-256) that the model flags as low-confidence. This is the
  only image selected by its output, so that the retake-photo flow can be shown.

Run from the repo root (needs the processed datasets and deployed weights):
    backend\\venv\\Scripts\\python.exe demo_data\\build_demo_data.py
"""

import json
import shutil
import subprocess
import sys
from pathlib import Path

import pandas as pd
from PIL import Image

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))

from ml.pipeline import MangoOrchardPipeline  # noqa: E402

OUT = REPO / "demo_data" / "images"
DISEASES = ["Anthracnose", "Bacterial Canker", "Powdery Mildew", "Sooty Mold"]
SOURCES = {
    "test": "MangoLeafBD (Ahmed et al. 2023, Data in Brief 47:108941; CC BY-NC 3.0), held-out test split",
    "external": "Mango Leaf Disease Dataset (Rahman et al. 2024, Mendeley doi:10.17632/7ghdbftp54.1; CC BY 4.0), "
                "external set",
    "pest": "Roboflow Universe school-vakkx/mango-fruit-fly v4 (CC BY 4.0), pest test split. Trap photo, not a "
            "mango tree",
}


def select():
    split = pd.read_csv(REPO / "ml/datasets/processed/disease/split.csv")
    test = split[split.split == "test"].sort_values("sha256")
    rows = []
    for label in DISEASES:
        for i, r in enumerate(test[test.label == label].head(2).itertuples(), 1):
            rows.append((f"{len(rows) + 1:02d}_{label.lower().replace(' ', '_')}_{i}.jpg", r.path, label, "test"))
    r = test[test.label == "Healthy"].iloc[0]
    rows.append((f"{len(rows) + 1:02d}_healthy.jpg", r.path, "Healthy", "test"))
    pest = pd.read_csv(REPO / "ml/datasets/processed/pest/split.csv")
    r = pest[(pest.split == "test") & (pest.source == "fruit_fly")].sort_values("sha256").iloc[0]
    rows.append((f"{len(rows) + 1:02d}_pest_trap_fruit_fly.jpg", r.image, f"{r.n_boxes} annotated Fruit Fly box(es)",
                 "pest"))
    return rows


def main():
    pipe = MangoOrchardPipeline(weather_fetcher=lambda lat, lon: None)
    det = pipe.disease_detector
    rows = select()
    ext = pd.read_csv(REPO / "ml/datasets/processed/external/manifest.csv")
    ext = ext[ext.excluded_reason.isna()].sort_values("sha256")
    for r in ext.itertuples():
        if det.predict(Image.open(REPO / r.path).convert("RGB"))["low_confidence"]:
            rows.append((f"{len(rows) + 1:02d}_unsure_external.jpg", r.path, r.label, "external"))
            break

    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)
    versions = {m["name"]: m["version"] for m in json.loads((REPO / "ml/model_registry.json").read_text())["models"]}
    commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=REPO, capture_output=True, text=True).stdout.strip()
    lines = [
        "# Demo images and the deployed models' actual outputs",
        "",
        f"Generated by `demo_data/build_demo_data.py` at commit `{commit}`; disease model "
        f"`{versions['disease_classifier']}`, pest model `{versions['pest_detector']}`, low-confidence threshold "
        f"{det.ood_threshold:.4f}. Selection rule: see the script docstring (deterministic, test split only, except "
        "the one external \"unsure\" image).",
        "",
        "The disease, confidence and lesion % below are what the app shows. The OHI column was computed with weather "
        "**excluded**, so it is reproducible. In the live app, the OHI also includes the current Open-Meteo weather "
        "and can differ by a few points.",
        "",
        "| File | Source | True label | Model output | Confidence | Retake photo? | Lesion % | OHI (no weather) | Tier |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for name, src, label, kind in rows:
        shutil.copyfile(REPO / src, OUT / name)
        if kind == "pest":
            res = pipe.analyze_orchard(None, OUT / name, scan_type="pest", generate_gradcam=False, output_dir=REPO / "demo_data" / ".tmp")
            dets = res["pest_intelligence"]["detections"]
            out = (f"{len(dets)} detection(s): " + ", ".join(sorted({d['pest_name'] for d in dets})) +
                   " (all labelled unverified: trained on non-mango data)") if dets else "no detections"
            confs = ", ".join(f"{d['confidence']:.2f}" for d in dets)
            ohi = res["orchard_health_index"]
            lines.append(f"| `{name}` | {SOURCES[kind]} | {label} | {out} | {confs} | n/a | n/a | "
                         f"{ohi['ohi_score'] if ohi['ohi_score'] is not None else 'none (no image-based component)'} | "
                         f"{ohi['health_status']} |")
            continue
        res = pipe.analyze_orchard(OUT / name, scan_type="disease", generate_gradcam=False, output_dir=REPO / "demo_data" / ".tmp")
        d = res["disease_diagnosis"]
        ohi = res["orchard_health_index"]
        lines.append(f"| `{name}` | {SOURCES[kind]} | {label} | {d['disease_name']} | {d['confidence']:.3f} | "
                     f"{'**yes**' if d['low_confidence'] else 'no'} | {d['lesion_severity_percentage']:.1f} | "
                     f"{ohi['ohi_score'] if ohi['ohi_score'] is not None else 'none'} | {ohi['health_status']} |")
    shutil.rmtree(REPO / "demo_data" / ".tmp", ignore_errors=True)
    lines += ["", "Images are redistributed under their licences, with attribution as listed in the Source column. "
              "MangoLeafBD is non-commercial only."]
    (REPO / "demo_data" / "MANIFEST.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
